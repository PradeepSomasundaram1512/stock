"""
Writes the forward test's current status into the paper (paper/results_forward_status.tex), so the paper's statement about it is generated, never typed.

Until the pre-registered minimum sample is met (300 matured signals AND 20 independent blocks) the paper says exactly how far along it is and reports no result.
Once it is met, the same command adds a results table (hypotheses H1 to H6, estimates with 95% intervals and Holm-adjusted p-values) and the paper text switches to it.

    python paper_forward_status.py                      pull data/forward_test.json from the bucket (needs gcloud), then write the tex
    python paper_forward_status.py path/to/forward.json use a local copy (the weekly cloud job writes it)
Then rebuild the paper (pdflatex/bibtex).
"""
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "paper" / "results_forward_status.tex"
BUCKET = "gs://project-0c776d86-067e-4f37-9ca-stock-scanner-data/forward_test.json"
NEED_S, NEED_B = 300, 20
HYP = [("H1_gated_minus_all", "H1: conf.\\ $\\geq 0.85$ vs.\\ all", "pct"), ("H2_spearman_conf_car", "H2: rank corr.\\ conf.--CAR", "rho"),
       ("H3_reversal_minus_universe", "H3: low-RSI vs.\\ universe", "pct"), ("H4_llm_minus_reversal", "H4: LLM vs.\\ low-RSI", "pct"),
       ("H5_lowrsi30_minus_all", "H5: lowest-RSI third vs.\\ all", "pct"), ("H6_biascorrected_alpha", "H6: bias-corrected alpha (primary)", "pct")]


def load(arg: str = None) -> dict:
    raw = Path(arg).read_text() if arg else subprocess.run(["gcloud", "storage", "cat", BUCKET], capture_output=True, text=True, check=True).stdout
    d = json.loads(raw)
    return d[0] if isinstance(d, list) else d


def render(o: dict, today: str) -> str:
    n, b = int(o.get("n_signals", 0)), int(o.get("n_blocks", 0))
    reached = n >= NEED_S and b >= NEED_B and "H1_gated_minus_all" in o
    if not reached:
        text = (f"As of {today}, {n} of the {NEED_S} matured signals and {b} of the {NEED_B} independent blocks required by the pre-registration had matured, "
                f"so no forward result is reported.")
        table = ""
    else:
        text = f"As of {today}, {n} matured forward signals in {b} independent blocks meet the pre-registered minimum; the results are in Table~\\ref{{tab:fwdresults}}."
        holm = o.get("holm_adjusted_p", {})
        rows = []
        for k, lab, kind in HYP:
            if k not in o:
                continue
            r = o[k]
            f = (lambda v: f"{v * 100:+.2f}") if kind == "pct" else (lambda v: f"{v:+.3f}")
            rows.append(f"{lab} & ${f(r['est'])}\\;[{f(r['lo'])},{f(r['hi'])}]$ & {holm.get(k, float('nan')):.2f} \\\\")
        table = ("\\begin{table}[t]\n\\centering\n\\caption{Pre-registered forward test: estimate (10-day CAR difference in \\%, rank correlation for H2) with 95\\% CI, and "
                 "Holm-adjusted $p$ across H1 to H6.}\n\\label{tab:fwdresults}\n\\footnotesize\\setlength{\\tabcolsep}{2pt}\n\\begin{tabular}{@{}lcc@{}}\n\\toprule\n"
                 "Hypothesis & Estimate & Holm $p$ \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    return ("% generated by paper_forward_status.py; do not edit\n"
            f"\\newcommand{{\\fwdStatusN}}{{{n}}}\n\\newcommand{{\\fwdStatusB}}{{{b}}}\n"
            f"\\newcommand{{\\fwdStatusText}}{{{text}}}\n"
            f"\\newcommand{{\\fwdStatusTable}}{{{table}}}\n")


def main():
    o = load(sys.argv[1] if len(sys.argv) > 1 else None)
    OUT.write_text(render(o, datetime.now(timezone.utc).strftime("%Y-%m-%d")))
    print(f"wrote {OUT.name}: {o.get('n_signals', 0)} matured signals, {o.get('n_blocks', 0)} blocks; verdict: {o.get('verdict', 'minimum sample reached')}")


if __name__ == "__main__":
    main()
