# RAG Configuration
RAG_TOP_K = 3
EMBEDDING_MODEL = "text-embedding-3-small"
CHUNK_SIZE = 500
CHUNK_OVERLAP = 50

# Risk thresholds
HIGH_VOLATILITY_THRESHOLD = 0.05  # 5% daily volatility (was 3%, too strict)
RSI_OVERBOUGHT = 70
