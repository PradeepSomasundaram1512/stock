"""
Build a clean, publishable copy of the project WITHOUT flipping the private repository public.

Why an export and not "make the repo public": the git history is fine (audited: no real credentials, only placeholder text), but the tracked files include raw
Yahoo Finance price panels, whose redistribution the provider's terms may not allow, and the live trading state. This copies only what should be public and stops
if anything secret-looking is in it.

    python tools/make_public_release.py [--out release]     (run from anywhere; writes <repo root>/release, git-ignored)

Excluded: raw price data (*.pkl, daily_panel_*, hourly_cache*), the live state (ai-stock-agent/data/ except the knowledge-base text), every .env file except the
.env.example templates, virtualenvs, caches, logs and the release folder itself.
Included on purpose: code, tests, docs, the paper and its generated tables, analysis outputs, the pre-registration, and the decision log the paper analyses.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, cwd=Path(__file__).parent, check=True).stdout.strip())
EXCLUDE = [
    r"\.pkl(\.gz)?$", r"/daily_panel_", r"/hourly_cache", r"(^|/)\.env($|\.(?!example$))", r"^ai-stock-agent/data/(?!knowledge_base/)",
    r"(^|/)venv[^/]*/", r"__pycache__/", r"\.log$", r"^release/", r"\.DS_Store$", r"\.(aux|bbl|blg|out)$",
]
SECRET = re.compile(r"sk-[A-Za-z0-9_-]{20,}|AIza[0-9A-Za-z_-]{35}|xox[bpa]-[0-9A-Za-z-]{10,}|discord(?:app)?\.com/api/webhooks/[0-9]+/[A-Za-z0-9_-]{20,}"
                    r"|-----BEGIN [A-Z ]*PRIVATE KEY-----|AKIA[0-9A-Z]{16}|gh[pousr]_[A-Za-z0-9]{30,}|GOCSPX-[A-Za-z0-9_-]{10,}")
PLACEHOLDER = re.compile(r"your|example|xxx|x{4,}|1234|abcd|\.\.\.|<|placeholder|here|test|fake|dummy|sample|0{6,}", re.I)


def tracked() -> list:
    return subprocess.run(["git", "ls-files"], capture_output=True, text=True, cwd=ROOT, check=True).stdout.splitlines()


def keep(path: str) -> bool:
    return not any(re.search(p, path) for p in EXCLUDE)


def scan(path: Path) -> list:
    try:
        text = path.read_text(errors="ignore")
    except Exception:            # noqa: BLE001 - binary
        return []
    return [m.group(0) for m in SECRET.finditer(text) if not PLACEHOLDER.search(m.group(0))]


def main() -> int:
    out = ROOT / (sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else "release")
    if out.exists():
        shutil.rmtree(out)
    files = tracked()
    kept, dropped = [f for f in files if keep(f)], [f for f in files if not keep(f)]
    problems = []
    for f in kept:
        src = ROOT / f
        if not src.is_file():
            continue
        if scan(src):
            problems.append(f)
            continue
        dst = out / f
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
    if problems:
        shutil.rmtree(out, ignore_errors=True)
        print("STOPPED: possible secrets in:", *problems, sep="\n  ")
        return 1
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    (out / "RELEASE_NOTES.md").write_text(
        "# Public release\n\nGenerated by `ai-stock-agent/tools/make_public_release.py`.\n\n"
        f"- {len(kept)} files included, {len(dropped)} excluded ({size / 1e6:.1f} MB).\n"
        "- **Raw Yahoo Finance price data is not included** (provider terms). Scripts that need prices re-download them; a re-download can shift secondary numbers slightly\n"
        "  (the portfolio-rule row moved by up to 0.3 percentage points between downloads; headline statistics agree to about eight decimals).\n"
        "- The live trading state and all `.env` files are not included; copy `.env.example` and fill in your own keys.\n"
        "- Not investment advice. This is a research and paper-trading project; its own audit found no detectable edge.\n\n"
        "## Excluded by pattern\n" + "\n".join(f"- `{p}`" for p in EXCLUDE) + "\n\n## Excluded files\n" + "\n".join(f"- {f}" for f in dropped) + "\n")
    print(f"release written to {out}: {len(kept)} files, {size / 1e6:.1f} MB; excluded {len(dropped)}")
    print("excluded files:", *dropped, sep="\n  ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
